## 어떻게 만들었나

**1. 위조·공유가 안 되는 QR**
QR 내용은 `LA1.<예약ID>.<30초 스텝>.<서명>` 형식이고, 서버 비밀키로 HMAC 서명합니다. ==30초마다 바뀌고 약 90초가 지나면 무효==가 됩니다. 같은 QR은 `token_uses` 테이블로 **한 번만** 통과시켜, 화면을 캡처해 친구에게 보내는 경우까지 막았습니다. !!캡처 공유가 제일 현실적인 공격이라고 봤음!!

**2. 판단은 전부 서버가 (fail-secure)**
단말은 QR을 읽어 전달만 하고, 시간·승인 상태·실습실 일치 여부는 모두 서버가 판단합니다. 서버에 연결되지 않으면 문은 열리지 않습니다. 단말마다 개별 키를 발급하고 서버에는 SHA-256 해시만 저장하며, 단말은 자기가 등록된 실습실의 예약만 열 수 있습니다. 비밀번호는 PBKDF2-SHA256(10만 회), 세션은 HttpOnly 서명 쿠키를 썼습니다.

